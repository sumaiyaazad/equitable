#!/usr/bin/env python3
"""
tab_04_components.py -- emit Tab 4: systems under test (benchmark components).

The seven engines the benchmark drives, with the pinned version each result was
produced against. Versions/digests are read from config/engines/pinned.yaml so
the table always matches the images the runs used, and the restate column is read
from each adapter's declared variants so it cannot drift from the code. Role and
integration mode are curated (they describe the adapter contract, not a config
value).

Inputs  : config/engines/pinned.yaml, src/adapters/*.py
Outputs : paper/.../tables/tab_04_components.tex
Runtime : instant
Run as  : python scripts/figures/tab_04_components.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from figures import load_module  # noqa: E402

_io = load_module("_io")
write_table = _io.write_table

PINNED = ROOT / "config" / "engines" / "pinned.yaml"

# Curated per-engine metadata (keyed by the id used in ENGINE_ORDER / configs).
# The restate column is NOT curated: it is read from supported_variants below.
ENGINE_META = {
    "reference":   ("reference backend", "in-proc.", "Python"),
    "materialize": ("SUT",           "container", "pgwire"),
    "risingwave":  ("SUT",           "container", "pgwire"),
    "ksqldb":      ("SUT",           "container", "Kafka, REST"),
    "flink":       ("SUT",           "cluster",   "SQL Gateway"),
    "spark":       ("SUT",           "cluster",   "standalone"),
    # Feldera is a released system scored like every other SUT. It was once
    # labelled a positive control for retraction, which contradicted the
    # abstract's count of six released systems under test.
    "feldera":     ("SUT",           "container", "DBSP, REST"),
}

ORDER = ["reference", "materialize", "risingwave", "ksqldb", "flink", "spark", "feldera"]


# in-process config keys -> engine id used in ENGINE_META / ENGINE_ORDER. Only
# the reference backend is scored in process; the PyFlink and PySpark pins
# describe comparison deployments and must not relabel the clusters.
IN_PROCESS_ALIAS = {"reference": "reference"}


def _short(engine: str, raw: str) -> str:
    """Sanitise a pinned-version string to a short, table-friendly label."""
    ver = str(raw).split(":")[-1].strip()
    if "==" in ver:
        ver = ver.split("==", 1)[1]

    ver = ver.replace("-scala_2.12", "")  # Flink image tag carries a Scala suffix
    # A path or free-text pin, such as the reference backend, is not a package
    # version label. Its implementation is bound by the source commit recorded
    # in each run manifest.
    if "/" in ver or " " in ver:
        return "source-commit" if engine == "reference" else ver.split()[0]
    return ver or "?"


def _versions() -> dict:
    """Map engine id -> short pinned version (reported_version, else image tag)."""
    doc = yaml.safe_load(PINNED.read_text()) or {}
    out: dict[str, str] = {}
    for name, spec in (doc.get("containers") or {}).items():
        if name not in ENGINE_META:
            continue
        raw = spec.get("reported_version") or spec.get("image", "")
        out[name] = _short(name, raw)
    # The reference entry resolves to the run's source-commit pin.
    for key, spec in (doc.get("in_process") or {}).items():
        engine = IN_PROCESS_ALIAS.get(key)
        if engine not in ENGINE_META:
            continue
        out[engine] = _short(engine, spec)
    return out


def _restate() -> dict:
    """Map engine id -> whether its adapter declares the D7 restate view.

    Read from each adapter's ``supported_variants`` rather than curated here, so
    the published capability cannot disagree with the code that ran. Adapters are
    constructed but never connected, and none imports its driver at module load.
    """
    from src.adapters import get_adapter

    return {
        name: "$\\cmark$" if "restate" in get_adapter(name).supported_variants
        else "$\\times$"
        for name in ORDER
    }


def _tex(text: str) -> str:
    return text.replace("_", "\\_")


def _render(versions: dict, restate: dict) -> str:
    lines = [
        "% Auto-generated by scripts/figures/tab_04_components.py — do not edit by hand.",
        "% Versions read from config/engines/pinned.yaml; restate read from src/adapters.",
        "\\begin{table}[!tb]",
        "\\centering",
        r"\caption{The seven execution backends: six released systems under test (SUT), pinned by Docker digest, and the in-process reference, pinned by source commit. \emph{Restate} says whether the engine can express the D7 view; $\times$ is a capability state, not a verdict.}",
        "\\label{tab:components}",
        "\\setlength{\\tabcolsep}{2pt}",
        "\\scriptsize",
        "\\begin{tabular}{@{}lllll@{}}",
        "\\toprule",
        "Engine & Role & Integration & Interface & Restate \\\\",
        "\\midrule",
    ]
    for name in ORDER:
        role, integ, iface = ENGINE_META[name]
        ver = versions.get(name, "?")
        label = f"{name} {{\\footnotesize\\texttt{{{_tex(ver)}}}}}"
        lines.append(
            f"{label} & {role} & {integ} & {_tex(iface)} & {restate[name]} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    versions = _versions()
    restate = _restate()
    write_table(_render(versions, restate), "tab_04_components")
    without = sum(1 for value in restate.values() if "times" in value)
    print(f"PASS: wrote Tab 4 ({len(ORDER)} engines; "
          f"{len(versions)} pinned versions read; "
          f"{without} without a restate formulation)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
