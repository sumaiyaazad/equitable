#!/usr/bin/env python3
"""
tab_03_schema.py -- emit Tab 3: the normalized row schema.

Structural HAND table, but the field list and the required
flags are pulled from src/schema/record.py so the table can never drift from the
code contract. Types and human meanings are curated here (they do not exist as
machine-readable metadata in the module).

Inputs  : src/schema/record.py (NORMALIZED_COLUMNS, REQUIRED_FIELDS)
Outputs : paper/.../tables/tab_03_schema.tex
Runtime : instant
Run as  : python scripts/figures/tab_03_schema.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))

from figures import load_module  # noqa: E402
from src.schema import record as schema_record  # noqa: E402

_io = load_module("_io")
write_table = _io.write_table


def _load_schema():
    """Return the authoritative schema module through its normal package path."""
    return schema_record


# Curated type + meaning per field (keyed by the record.py column name).
FIELD_INFO = {
    "event_time_utc":    ("ISO-8601", "Observation time in UTC; the only clock used for bucketing"),
    "ingest_time_utc":   ("ISO-8601", "System ingest time in UTC; never used for buckets"),
    "processing_order":  ("int",      "Replay arrival sequence for provenance and diagnostics"),
    "entity":            ("string",   "Aggregation subject: station, symbol, player, zone, or drive"),
    "metric":            ("string",   "Measured quantity, such as pm25, trade\\_price, speed, or fare"),
    "value":             ("float",    "Scalar measurement"),
    "topic":             ("string?",  "Source stream identifier when available"),
    "dedupe_id":         ("string",   "SHA-256 of source namespace, stable source event ID, and metric"),
    "source_record_type":("string",   "Base rows require \\texttt{data}; \\texttt{restatement} is D7-only"),
}


def _tex_field(name: str) -> str:
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def _render(columns, required) -> str:
    req = set(required)
    lines = [
        "% Auto-generated by scripts/figures/tab_03_schema.py — do not edit by hand.",
        "% Field list + required flags are read from src/schema/record.py.",
        "\\begin{table}[!tb]",
        "\\centering",
        "\\caption{The normalized row schema, enforced at ingestion: a row that "
        "fails validation is rejected before it changes state. Aggregates are "
        "keyed on $(\\textit{bucket},\\textit{entity},\\textit{metric})$.}",
        "\\label{tab:schema}",
        # A one-column table in the conference class leaves the Meaning column
        # about a third of the line once the typewriter field names are set,
        # and justified text there opens word-wide gaps. Smaller type, tighter
        # padding, and a ragged-right Meaning column keep it readable in both.
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabularx}{\\columnwidth}{@{}llc>{\\raggedright\\arraybackslash}X@{}}",
        "\\toprule",
        "Field & Type & Req. & Meaning \\\\",
        "\\midrule",
    ]
    for name in columns:
        typ, meaning = FIELD_INFO.get(name, ("?", "?"))
        mark = "$\\cmark$" if name in req else "$\\circ$"
        lines.append(f"{_tex_field(name)} & {typ} & {mark} & {meaning} \\\\")
    lines += [
        "\\midrule",
        "\\multicolumn{4}{@{}p{\\columnwidth}@{}}{\\footnotesize "
        "$\\cmark$ required; $\\circ$ optional. "
        "\\texttt{string?} is a string that may be missing or empty. "
        "\\texttt{supersedes} is an additional D7-only column, a restatement's "
        "pointer to the \\texttt{dedupe\\_id} it corrects, and is not part of the "
        "base schema.} \\\\",
        "\\bottomrule",
        "\\end{tabularx}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    schema = _load_schema()
    columns = list(schema.NORMALIZED_COLUMNS)
    required = list(schema.REQUIRED_FIELDS)
    write_table(_render(columns, required), "tab_03_schema")
    print(f"PASS: wrote Tab 3 ({len(columns)} fields, {len(required)} required)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
