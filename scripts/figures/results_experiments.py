#!/usr/bin/env python3
"""Emit the prose and table for the three follow-up experiments.

  results_disorder.tex     how much disorder an arrival-ordered latest needs
  results_parallel.tex     D3 replay drift against parallelism
  results_cost.tex         wall time of the repair against the arrival form
  tab_22_parallel_cost.tex one small table carrying both measured series

Every number and every qualitative claim is computed from the promoted blocks,
and each sentence has a branch for the opposite outcome, so a rerun that moves
a result moves the sentence with it. `--*-run` paths render a preview from
unpromoted runs; a render for submission reads promoted evidence only.
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from figures import load_module  # noqa: E402

_io = load_module("_io")
_disorder_fig = load_module("fig_06_disorder")

HEADER = "% Auto-generated by scripts/figures/results_experiments.py -- do not edit.\n"
LABEL = {"finance_markets": "finance", "environment_airquality": "air quality",
         "sports_football": "football", "transportation_taxi": "taxi"}


def _pct(x: float) -> str:
    return f"{100 * x:.0f}\\%"


def _english(items: List[str]) -> str:
    items = list(items)
    if not items:
        return "none"
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " and " + items[-1]


def _load(block: str, path: Optional[str]) -> Dict[str, Any]:
    if path:
        return json.loads(Path(path).read_text())
    summaries = _io.load_summaries(block)
    if not summaries:
        raise SystemExit(f"FAIL: promote {block} first (or pass a preview run)")
    return summaries[-1]


def disorder_prose(summary: Dict[str, Any]) -> str:
    rows = summary.get("rows") or []
    exposure = {(r["domain"], r["grain"], str(r["window"])): r
                for r in rows if r.get("kind") == "exposure"}
    series = [(d, g) for d, (g, *_rest) in _disorder_fig.SERIES.items()
              if (d, g, "0") in exposure]

    def at(window: str) -> List[str]:
        return [f"{_pct(exposure[(d, g, window)]['wrong_fraction'])} of "
                f"{LABEL[d]} keys"
                for d, g in series if (d, g, window) in exposure]

    ordered_clean = all(exposure[(d, g, "0")]["wrong_keys"] == 0 for d, g in series)
    parts = []
    parts.append("With events in order, no key is wrong." if ordered_clean else
                 "Even with events in order some keys are wrong, so the sweep "
                 "does not isolate delivery order.")
    if all((d, g, "3") in exposure for d, g in series):
        parts.append(
            "Displacing rows by at most three event-time steps already makes the "
            f"latest value wrong for {_english(at('3'))}.")
    if all((d, g, "100") in exposure for d, g in series):
        vals = [exposure[(d, g, "100")]["wrong_fraction"] for d, g in series]
        parts.append(
            f"At D2's displacement the share ranges from {_pct(min(vals))} to "
            f"{_pct(max(vals))}.")
    # Which domain is least exposed, and why, read from the data.
    if all((d, g, "10") in exposure for d, g in series):
        low = min(series, key=lambda s: exposure[(s[0], s[1], "10")]["wrong_fraction"])
        high = max(series, key=lambda s: exposure[(s[0], s[1], "10")]["wrong_fraction"])
        parts.append(
            f"Exposure depends on the data more than on the disorder. "
            f"{LABEL[high[0]].capitalize()} keys, with many close events per "
            f"bucket, are exposed almost at once. {LABEL[low[0]].capitalize()} "
            "keys stay nearly correct until the displacement is large.")
    engine = [r for r in rows if r.get("kind") == "engine"
              and r.get("status") == "measured"]
    if engine:
        on_curve = sum(
            1 for r in engine
            if r.get("arrival_wrong_keys")
            == exposure[(r["domain"], r["grain"], str(r["window"]))]["wrong_keys"])
        repair_ok = sum(1 for r in engine if r.get("contract_wrong_keys") == 0)
        engines = _io.sort_engines({r["engine"] for r in engine})
        n = len(engine)
        # Say where the engines were actually run, so the oracle's curves are
        # not read as engine measurements at every displacement.
        wins = sorted({str(r["window"]) for r in engine},
                      key=lambda w: (not w.isdigit(), int(w) if w.isdigit() else 0))
        disp = _english(["a full shuffle" if w == "shuffle" else w for w in wins])
        words = ("no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine")
        word = lambda k: words[k] if k < len(words) else f"{k:,}"
        parts.append(
            f"The {word(len(engines))} engines, {_english(engines)}, were replayed at "
            f"{word(len(wins))} displacements, {disp}, {n:,} cells in all, and "
            + ("every one landed on its domain's curve. " if on_curve == n else
               f"{on_curve:,} of them landed on their domain's curve. ")
            + ("Every repaired view matches" if repair_ok == n else
               f"{repair_ok:,} of the {n:,} repaired views match")
            + " the oracle at every displacement.")
    return " ".join(parts)


def _drift_by(summary: Dict[str, Any]) -> Dict[str, Dict[int, Dict[str, Any]]]:
    out: Dict[str, Dict[int, Dict[str, Any]]] = {}
    for r in summary.get("rows") or []:
        if r.get("status") != "measured":
            continue
        cell = out.setdefault(r["engine"], {}).setdefault(
            int(r["parallelism"]), {"drift": 0, "keys": 0, "domains": 0,
                                    "drifting_domains": 0, "equivalent": 0})
        cell["drift"] += int(r.get("drift_keys") or 0)
        cell["keys"] += int(r.get("keys") or 0)
        cell["domains"] += 1
        cell["drifting_domains"] += int(bool(r.get("drift_keys")))
        cell["equivalent"] += int(bool(r.get("oracle_equivalent")))
    return out


def parallel_prose(summary: Dict[str, Any]) -> str:
    """Describe each engine's drift TREND across parallelism, read from the
    data: zero at one and rising, flat at every level, or neither."""
    by = _drift_by(summary)
    if not by:
        return ""
    parts = []
    for e in _io.sort_engines(by):
        levels = sorted(by[e])
        drift = [by[e][p]["drift"] for p in levels]
        if 1 not in by[e] or len(levels) < 2:
            continue
        at_one = by[e][1]["drift"]
        rising = all(b >= a for a, b in zip(drift, drift[1:])) and drift[-1] > drift[0]
        flat = at_one > 0 and max(drift) <= 1.5 * min(drift)
        if at_one == 0 and rising:
            parts.append(
                f"Two replays of {e} are bit-identical at parallelism one, and "
                "the number of keys that differ grows as parallelism rises.")
        elif at_one == 0 and not any(drift):
            parts.append(f"Replays of {e} are bit-identical at every level.")
        elif flat:
            parts.append(
                f"Replays of {e} differ on about the same number of keys at "
                "every level, including one, so parallel combination does not "
                "explain its drift.")
        else:
            parts.append(
                f"Replays of {e} differ at parallelism one as well, with no "
                "clear trend across levels.")
    total = sum(c["domains"] for e in by for c in by[e].values())
    equivalent = sum(c["equivalent"] for e in by for c in by[e].values())
    parts.append(
        ("Every replay stays" if equivalent == total else
         f"{equivalent} of {total} replays stay")
        + " within the contract tolerance of the oracle, so the drift is a "
        "reproducibility problem, not a wrong result.")
    return " ".join(parts)


def _ratios(summary: Dict[str, Any]) -> Dict[str, Dict[str, float]]:
    out: Dict[str, Dict[str, float]] = {}
    for r in summary.get("ratios") or []:
        out.setdefault(r["engine"], {})[r["domain"]] = float(r["repair_over_arrival"])
    return out


def cost_prose(summary: Dict[str, Any]) -> str:
    ratios = _ratios(summary)
    values = [v for d in ratios.values() for v in d.values()]
    if not values:
        return ""
    lo, hi, med = min(values), max(values), statistics.median(values)
    rows = int(summary.get("prefix_rows") or 0)
    text = (
        f"Over {rows:,} reordered rows, the repaired view takes between "
        f"{lo:.2f} and {hi:.2f} times as long as the arrival-ordered one, "
        f"with a median of {med:.2f}, measured one engine at a time.")
    if hi <= 1.25:
        text += " Where an engine can state the event-time rule, stating it is cheap."
    elif med <= 1.25:
        text += (" The repair is cheap on most engines; "
                 + _english([e for e, d in ratios.items() if max(d.values()) > 1.25])
                 + " pays a visible price.")
    else:
        text += " The repair has a real cost, which a query author should weigh."
    return text + " ksqlDB has no event-time formulation to time."


def parallel_cost_table(par: Dict[str, Any], cost: Dict[str, Any]) -> str:
    by = _drift_by(par)
    ratios = _ratios(cost)
    levels = sorted({p for e in by.values() for p in e})
    domains = sorted({d for e in ratios.values() for d in e})
    engines = _io.sort_engines(set(by) | set(ratios))
    dom_label = {"finance_markets": "fin.", "transportation_taxi": "taxi"}
    head_p = " & ".join(str(p) for p in levels)
    head_c = " & ".join(dom_label.get(d, d) for d in domains)
    lines = [
        HEADER.rstrip(),
        r"\begin{table}[!tb]",
        r"\centering",
        r"\caption{Left: keys whose sum differs between two replays, summed "
        r"over the five domains, by parallelism; a dash marks an engine the "
        r"sweep did not run. Right: time of the repaired "
        r"view divided by time of the arrival-ordered view, serialized, on the "
        + _english([LABEL.get(d, d) for d in domains]) + r" logs.}",
        r"\label{tab:parallel-cost}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        rf"\begin{{tabular}}{{@{{}}l{'r' * len(levels)}@{{\quad}}{'r' * len(domains)}@{{}}}}",
        r"\toprule",
        rf" & \multicolumn{{{len(levels)}}}{{c}}{{Drifting keys at parallelism}}"
        rf" & \multicolumn{{{len(domains)}}}{{c}}{{Repair $\div$ arrival}} \\",
        rf"\cmidrule(lr){{2-{1 + len(levels)}}}\cmidrule(l){{{2 + len(levels)}-{1 + len(levels) + len(domains)}}}",
        rf"Engine & {head_p} & {head_c} \\",
        r"\midrule",
    ]
    for e in engines:
        drift = [f"{by[e][p]['drift']:,}" if e in by and p in by[e] else "--"
                 for p in levels]
        cost_cells = [f"{ratios[e][d]:.2f}" if e in ratios and d in ratios[e] else "--"
                      for d in domains]
        lines.append(f"{e} & " + " & ".join(drift + cost_cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--disorder-run")
    parser.add_argument("--parallel-run")
    parser.add_argument("--cost-run")
    parser.add_argument("--tables-only", action="store_true",
                        help="write tab_22_parallel_cost.tex only, not the "
                             "three prose blocks (the public artifact)")
    args = parser.parse_args()
    disorder = _load("disorder_sweep", args.disorder_run)
    parallel = _load("parallelism_sweep", args.parallel_run)
    cost = _load("formulation_cost", args.cost_run)
    if not args.tables_only:
        _io.write_table(HEADER + disorder_prose(disorder) + "\n", "results_disorder")
        _io.write_table(HEADER + parallel_prose(parallel) + "\n", "results_parallel")
        _io.write_table(HEADER + cost_prose(cost) + "\n", "results_cost")
    _io.write_table(parallel_cost_table(parallel, cost), "tab_22_parallel_cost")
    if args.tables_only:
        print("PASS: wrote the parallelism and cost table")
    else:
        print("PASS: wrote the follow-up experiment prose and table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
