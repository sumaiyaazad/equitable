#!/usr/bin/env python3
"""Emit Table 12: every validity control behind RQ1.

Reads the promoted oracle-verification, boundary, mutation, and D7S sweep
blocks and writes one row per control. The table carries every count, so the
RQ1 prose written by results_narrative.py interprets the controls without
restating their numbers.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from figures import load_module  # noqa: E402

_io = load_module("_io")
load_summaries = _io.load_summaries
write_table = _io.write_table


def _latest(block: str) -> Dict[str, Any]:
    rows = load_summaries(block)
    return rows[-1] if rows else {}


def _d7s_scope(d7s: Dict[str, Any]) -> str:
    """Say where the grid separates, or that the complete grid never does."""
    if not int(d7s["separating_cells"]):
        return "all-negative grid, retained rather than retried"
    domains = sum(
        int(count) > 0 for count in d7s["separating_by_domain"].values())
    return (
        f"{domains} of {len(d7s['domains'])} domains; smallest separating "
        f"alpha {d7s['min_separating_alpha']:g}")


def _render(
    oracle: List[Dict[str, Any]],
    boundary_rows: List[Dict[str, Any]],
    mutation: Dict[str, Any],
    d7s: Dict[str, Any],
) -> str:
    oracle = _io.validate_oracle_summaries(oracle)
    boundary_rows = _io.validate_boundary_cells(boundary_rows)
    mutation = _io.validate_mutation_summary(mutation)
    d7s = _io.validate_d7s_summary(d7s)

    equivalent = sum(row.get("all_equivalent") is True for row in oracle)
    injected = sum(int(row["injected"]) for row in boundary_rows)
    rejected = sum(int(row["rejected"]) for row in boundary_rows)
    engine_rejected = sum(int(row["engine_rejected"]) for row in boundary_rows)
    classes = max(int(row["violation_class_count"]) for row in boundary_rows)
    cells = mutation.get("rows") or []
    mutation_domains = len({row.get("domain") for row in cells})
    off = [row for row in cells if not row.get("is_target") and not row.get("vacuous")]
    collateral = [row for row in off if row.get("detected") is True]
    caught = int(mutation.get("diagonal_caught", 0))
    total = int(mutation.get("diagonal_total", 0))
    lines = [
        r"% Auto-generated by scripts/figures/tab_12_validation.py -- do not edit.",
        r"\begin{table}[!tb]",
        r"\centering",
        r"\caption{Validity controls. Each row checks the benchmark itself, not "
        r"an engine. Off-target detections are reported.}",
        r"\label{tab:validation}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabularx}{\columnwidth}{@{}lrr>{\raggedright\arraybackslash}X@{}}",
        r"\toprule",
        r"Control & Count & Of & Scope \\",
        r"\midrule",
        f"Oracle agreement & {equivalent} & {len(oracle)} & domains at one "
        f"million rows; reference, pandas, and DuckDB agree pairwise at both "
        f"grains \\\\",
        f"Boundary, offline oracle & {rejected} & {injected} & malformed rows "
        f"rejected, {classes} violation classes in equal number \\\\",
        f"Boundary, reference engine & {engine_rejected} & {injected} & "
        f"malformed rows rejected; aggregates unchanged \\\\",
        f"Targeted mutants & {caught} & {total} & detected, one defect per "
        f"condition on {mutation_domains} domains \\\\",
        f"Off-target non-detections & {len(off) - len(collateral)} & {len(off)} & "
        f"{len(collateral)} off-target detections \\\\",
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    oracle = load_summaries("oracle_verification")
    boundary = _latest("boundary")
    mutation = _latest("mutation")
    d7s = _latest("d7s_sweep")
    if (len(oracle) != len(_io.CONTRACT_DOMAINS) or not boundary
            or not mutation or not d7s):
        print("FAIL: promote oracle-verification, boundary, mutation, and D7S "
              "results for Table 12.")
        return 1
    try:
        table = _render(oracle, boundary.get("rows") or [], mutation, d7s)
    except ValueError as exc:
        print(f"FAIL: cannot generate Table 12: {exc}")
        return 1
    write_table(table, "tab_12_validation")
    ok = bool(mutation.get("pass"))
    print(f"PASS: wrote Table 12 (controls_pass={ok})")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
