#!/usr/bin/env python3
"""
tab_02_domains.py -- emit Tab 2: five-domain benchmark slate + scaling axes.

Reads the domain registry YAML files and writes a LaTeX table fragment for
\\input in the paper drafts.

Inputs  : config/domains/*.yaml
Outputs : paper/.../tables/tab_02_domains.tex
Runtime : instant
Run as  : python scripts/figures/tab_02_domains.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from figures import load_module  # noqa: E402

_io = load_module("_io")
write_table = _io.write_table

DOMAINS_DIR = ROOT / "config" / "domains"


def _load_domains() -> list[dict]:
    paths = sorted(DOMAINS_DIR.glob("*.yaml"))
    if not paths:
        print(f"FAIL: no domain configs under {DOMAINS_DIR}/")
        print("  Add domain YAML files under config/domains/ first.")
        raise SystemExit(1)
    rows = []
    for path in paths:
        doc = yaml.safe_load(path.read_text()) or {}
        if "domain" not in doc:
            continue
        metrics = doc.get("metrics") or []
        metric_names = ", ".join(m.get("name", "?") for m in metrics)
        buckets = doc.get("buckets") or {}
        fine = buckets.get("fine", "?")
        coarse = buckets.get("coarse", "?")
        source = (doc.get("source") or {}).get("name", "?")
        rows.append({
            "domain": doc["domain"],
            "source": source,
            "entity": doc.get("entity", "?"),
            "metrics": metric_names,
            "fine": fine,
            "coarse": coarse,
        })
    rows.sort(key=lambda r: r["domain"])
    return rows


def _tex_escape(text: str) -> str:
    return (
        text.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("&", "\\&")
        .replace("%", "\\%")
    )


def _render(rows: list[dict]) -> str:
    # Full-width (table*) with a wrapping X column for the metric list, so the
    # long source names / metric lists never bleed past the margin.
    lines = [
        "% Auto-generated by scripts/figures/tab_02_domains.py — do not edit by hand.",
        "\\begin{table*}[!tb]",
        "\\centering",
        "\\caption{The five real-world domains. Each maps into the schema of "
        "\\tabref{tab:schema}; buckets give the fine and coarse grains.}",
        "\\label{tab:domains}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\small",
        "\\begin{tabularx}{\\textwidth}{@{}lllXl@{}}",
        "\\toprule",
        "Domain & Source & Entity & Metrics & Buckets, fine then coarse \\\\",
        "\\midrule",
    ]
    for row in rows:
        buckets = f"{row['fine']}, {row['coarse']}"
        lines.append(
            " & ".join(
                _tex_escape(str(row[k]))
                for k in ("domain", "source", "entity", "metrics")
            )
            + f" & {_tex_escape(buckets)} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabularx}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    rows = _load_domains()
    write_table(_render(rows), "tab_02_domains")
    print(f"PASS: wrote Tab 2 ({len(rows)} domain(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
