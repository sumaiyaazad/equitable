#!/usr/bin/env python3
"""
tab_11_witnesses.py -- emit Tab 11: one public witness per correctness condition.

Renders the entries of the curated incident inventory that carry
`representative: true` as a seven-row table: condition, the witness (hyperlinked
to its primary source), and one sentence on how it violates the condition.

The claim this table licenses is EXISTENTIAL COVERAGE -- every correctness condition
has at least one confirmed real-world witness. It says nothing about relative
frequency, which is why the retired Fig 5 bar chart (per-condition counts) was
dropped: bar heights encoded a prevalence claim the curation procedure cannot
support. Do NOT reintroduce counts here, and do not describe the inventory as a
survey -- the search universe is not frozen, candidates are not deduplicated,
and only a hand-picked shortlist was screened.

Unlike the other generators this one reads a curated YAML rather than
results/<block>/, so it needs no promotion step.

Inputs  : data/incidents.yaml
Outputs : paper/{journal,conference}_draft/tables/tab_11_witnesses.tex
Runtime : instant
Run as  : python scripts/figures/tab_11_witnesses.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from figures import load_module  # noqa: E402

_io = load_module("_io")
write_table = _io.write_table

SEED = ROOT / "data" / "incidents.yaml"

# The seven correctness conditions C1--C7. Every one must have a representative witness --
# a gap means the diagnostic suite has a branch with no real-world grounding, so
# this generator fails loudly rather than silently emitting a short table.
CONDITIONS = (1, 2, 3, 4, 5, 6, 7)

REQUIRED_FIELDS = ("condition", "url", "condition_name", "paper_label", "paper_text")


def _load_representatives() -> tuple[dict[int, dict], int, int]:
    """Return ({condition: representative entry}, total incidents, engine count).

    The two counts describe the WHOLE inventory, not just the representatives --
    the caption reports the inventory's size so the table does not look like the
    only evidence that exists.
    """
    if not SEED.is_file():
        print(f"FAIL: curated inventory not found at {SEED}")
        raise SystemExit(1)

    doc = yaml.safe_load(SEED.read_text()) or {}
    incidents = doc.get("incidents") or []
    if not incidents:
        print(f"FAIL: no `incidents:` entries in {SEED}")
        raise SystemExit(1)

    chosen: dict[int, dict] = {}
    for entry in incidents:
        if not entry.get("representative"):
            continue
        missing = [f for f in REQUIRED_FIELDS if not entry.get(f)]
        if missing:
            print(f"FAIL: representative entry {entry.get('id', '?')} is missing "
                  f"{', '.join(missing)}")
            raise SystemExit(1)
        condition = entry["condition"]
        if condition in chosen:
            print(f"FAIL: conditions must have exactly one representative, but "
                  f"condition {condition} has both {chosen[condition]['id']} and "
                  f"{entry['id']}")
            raise SystemExit(1)
        chosen[condition] = entry

    gaps = [c for c in CONDITIONS if c not in chosen]
    if gaps:
        print("FAIL: no representative witness for correctness condition(s): "
              f"{', '.join(f'L{c}' for c in gaps)}")
        print(f"  Mark one confirmed entry per condition with `representative: true`")
        print(f"  in {SEED}, and give it condition_name / paper_label / paper_text.")
        raise SystemExit(1)

    return chosen, len(incidents), len({e.get("engine") for e in incidents})


def _render(rows: dict[int, dict], total: int, engines: int) -> str:
    # ONE row per condition, never one row per incident. Listing every witness
    # would give L7 three rows and L1 one, re-encoding the per-condition
    # frequency that retiring Fig 5 was meant to remove -- a table with unequal
    # rows per group reads as a bar chart. The inventory SIZE is safe to state
    # (it is a total, not a distribution), so the caption carries it and the
    # artifact carries the rest.
    lines = [
        r"% Auto-generated by scripts/figures/tab_11_witnesses.py -- do not edit by hand.",
        r"% Source: data/incidents.yaml (entries with representative: true).",
        r"% EXISTENTIAL COVERAGE ONLY -- this table says each correctness condition has at",
        r"% least one real-world witness. It says nothing about relative frequency and",
        r"% must not be described as a survey. Do NOT cite candidate counts",
        r"% The bold lead-in phrases are the condition names; they must stay in sync",
        r"% with the condition names C1--C7 given in Sec. \ref{sec:conditions}.",
        r"\begin{table}[!tb]",
        r"  \centering",
        r"  \small",
        r"  \caption{One public, confirmed incident per condition. It shows that",
        r"  each failure mode occurs, not how often; the artifact lists all",
        rf"  {total} confirmed reports across {engines} engines.}}",
        r"  \label{tab:witnesses}",
        r"  \begin{tabularx}{\columnwidth}{@{}l l X@{}}",
        r"    \toprule",
        r"    & \textbf{Witness} & \textbf{Condition, and how it is violated} \\",
        r"    \midrule",
    ]
    for condition in CONDITIONS:
        entry = rows[condition]
        lines.append(
            f"    L{condition} & \\href{{{entry['url']}}}{{{entry['paper_label']}}}"
        )
        lines.append(
            f"       & \\textbf{{{entry['condition_name']}.}} {entry['paper_text']} \\\\"
        )
    lines += [
        r"    \bottomrule",
        r"  \end{tabularx}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    rows, total, engines = _load_representatives()
    write_table(_render(rows, total, engines), "tab_11_witnesses")
    named = ", ".join(sorted({rows[c]["engine"] for c in CONDITIONS}))
    print(f"PASS: 7/7 correctness conditions have a representative witness ({named})")
    print(f"      inventory: {total} confirmed incidents across {engines} engines")


if __name__ == "__main__":
    main()
